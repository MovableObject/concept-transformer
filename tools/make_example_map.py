"""Build the example map the menu opens: a finished graph on the owner's test inputs, with three recipes already run
by Claude Opus (results from tests/results/recipes_opus.json, all three results per step from the gallery where a step
was reused). Writes web/src/lib/exampleMap.ts. Costs nothing to serve: the results ship with the page.

    python tools/make_example_map.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REC = json.load(open(os.path.join(ROOT, "tests", "results", "recipes_opus.json"), encoding="utf-8"))["chains"]
GAL = json.load(open(os.path.join(ROOT, "tests", "results", "opus_gallery.json"), encoding="utf-8"))["jobs"]
PIGEONS, APARTMENT = "A man feeding pigeons on a park bench", "Moving into an empty apartment"

# (chain id in recipes_opus.json, moves in order, column x, input node ids per step)
CHAINS = [
    ("S16|0", ["misuse", "documentation"], 0, [["c1"], ["s0"]]),
    ("S6|0", ["rule_break", "time_shift"], 340, [["c1"], ["s0"]]),
    ("C13|2", ["bisociation", "pov_shift", "documentation"], 760, [["c2", "c1"], ["s0"], ["s1"]]),
]


def gallery_full(move, first):
    for j in GAL.values():
        if j.get("mode") == "ideas" and j["move"] == move and j.get("variants") and j["variants"][0] == first:
            return j["variants"]
    return [first]


def main():
    nodes = {
        "c1": {"id": "c1", "kind": "concept", "text": PIGEONS, "x": 160, "y": 0},
        "c2": {"id": "c2", "kind": "concept", "text": APARTMENT, "x": 760, "y": 0},
        "n1": {"id": "n1", "kind": "note", "x": -300, "y": 0,
               "text": "An example map, already run by Claude Opus. Select any box to see its settings and all three "
                       "results on the right. Three recipes: Wrong Tool then The Paperwork (left), Break Its Rule then "
                       "Another Era (middle), and a two-box recipe on the right. Ctrl+Z brings back your own map."},
    }
    order = ["n1", "c1", "c2"]
    display = None
    for ci, (cid, moves, x, refs) in enumerate(CHAINS):
        st = REC[cid]
        ids = []
        for si, move in enumerate(moves):
            tid = f"t{ci}{si}"
            full = st["full"][si] if st["full"][si] and len(st["full"][si]) > 1 else gallery_full(move, st["outs"][si])
            inputs = [ids[int(r[1:])] if r.startswith("s") else r for r in refs[si]]
            nodes[tid] = {"id": tid, "kind": "transform", "moveIds": [move], "inputs": inputs, "x": x, "y": 190 * (si + 1),
                          "mode": "ideas", "words": 30, "variants": full}
            ids.append(tid)
            order.append(tid)
        if ci == 0:
            display = ids[-1]
    data = {"nodes": nodes, "order": order, "display": display, "selected": display}
    out = os.path.join(ROOT, "web", "src", "lib", "exampleMap.ts")
    open(out, "w", encoding="utf-8").write(
        "// Generated by tools/make_example_map.py from the Opus recipe test (2026-10-17). Do not edit by hand.\n"
        "export const EXAMPLE_MAP = " + json.dumps(data, ensure_ascii=False, indent=1) + " as const\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
